"""Collect every number the report uses into docs/report/raw_material.md, read from result files or recomputed here.

Run from the repo root:  python -m src.report_material
Also writes results/error_analysis_student_test.csv (final pipeline errors on student_test, by type).
"""
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from . import network, viterbi
from .run_viterbi import load_candidates, load_obs_labels

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
OUT = ROOT / "docs" / "report" / "raw_material.md"


def md(df, floatfmt="{:.4f}"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def wavg(v, w):
    return float(np.average(v, weights=w))


def error_analysis():
    """Decode student_test with the final pipeline and classify every error."""
    cfg = json.loads((ROOT / "models/classifier_config.json").read_text())
    model = joblib.load(ROOT / "models/classifier.joblib")
    params = viterbi.HMMParams.from_json(ROOT / "models/hmm_config.json")
    cands, labels = load_candidates("student_test"), load_obs_labels("student_test")
    rows = []
    for tid, c in cands.items():
        g = network.RoadGraph(network.load_trip(tid, "student_test"))
        prob = model.predict_proba(c[cfg["feature_columns"]])[:, 1]
        pred = viterbi.decode(c, params.emission_weight * viterbi.classifier_emission_logp(prob), g, params)
        lab = labels[tid]
        ref = lab.ref_arc_id.to_numpy(np.int64)
        arcs = g.trip.arcs
        d_ref, t_ref = g.snap(g.trip.gps_xy, ref)
        d_pred, _ = g.snap(g.trip.gps_xy, pred)
        twin = (arcs[pred, 0] == arcs[ref, 1]) & (arcs[pred, 1] == arcs[ref, 0])
        adj = ~twin & ((arcs[pred, 1] == arcs[ref, 0]) | (arcs[ref, 1] == arcs[pred, 0]))
        rows.append(pd.DataFrame({
            "trip_id": tid, "obs_idx": np.arange(len(ref)), "correct": pred == ref,
            "stationary": lab.stationary.to_numpy(bool),
            "error_type": np.where(pred == ref, "correct", np.where(twin, "wrong direction (twin arc)",
                                   np.where(adj, "adjacent arc", "other arc"))),
            "dist_to_junction_m": np.minimum(t_ref, 1 - t_ref) * g.arc_len[ref],
            "dist_gps_to_ref_m": d_ref, "dist_gps_to_pred_m": d_pred,
            "pred_on_route": np.isin(pred, g.trip.route)}))
    df = pd.concat(rows, ignore_index=True)
    df.to_csv(R / "error_analysis_student_test.csv", index=False)
    return df


def main():
    s = []
    add = s.append
    add("# PathSnap report: raw material\n\nGenerated by `src/report_material.py` from files in `results/`. "
        "Every number below comes from a result file or is recomputed by this script.\n")

    inv = pd.read_csv(R / "eda/trip_inventory.csv", dtype={"trip_id": str})
    add("## Data (results/eda/trip_inventory.csv)\n")
    rows = []
    for part, g in inv.groupby("partition", sort=False):
        rows.append({"partition": part, "trips": len(g), "gps_points": int(g.n_points.sum()),
                     "frac_steps_1s": wavg(g.frac_dt_eq_1, g.n_points - 1),
                     "parked_frac": wavg(g.stationary_frac, g.n_points),
                     "trips_gap_gt30s": int((g.gaps_gt_30s > 0).sum()), "max_gap_s": float(g.dt_max_s.max()),
                     "nodes_median": float(g.n_nodes.median()), "arcs_min": int(g.n_arcs.min()), "arcs_max": int(g.n_arcs.max()),
                     "frac_two_way_mean": float(g.frac_arcs_two_way.mean()),
                     "largest_weak_comp_mean": float(g.largest_weak_frac.mean()),
                     "trips_route_not_fully_connected": int((g.route_consecutive_connected_frac < 1).sum()),
                     "trips_route_repeats_arc": int((g.route_unique_arcs < g.n_route_arcs).sum())})
    add(md(pd.DataFrame(rows)))
    add(f"\n- NaN values: {int(inv.nan_values.sum())}; invalid coords: {int(inv.invalid_coords.sum())}; "
        f"duplicate timestamps: {int(inv.duplicate_timestamps.sum())}; non-increasing timestamps: {int(inv.non_increasing_timestamps.sum())}")
    add(f"- GPS-to-route distance, moving points, median of per-trip medians: {inv.gps_to_route_p50_moving_m.median():.2f} m")
    for part, g in inv.groupby("partition", sort=False):
        add(f"- {part}: reference route within 30 m / 50 m of a fix (point-weighted): "
            f"{np.average(g.route_within_r30_frac, weights=g.n_points):.4f} / {np.average(g.route_within_r50_frac, weights=g.n_points):.4f}")
    add(f"- Longitude range {inv.lon_min.min():.1f} to {inv.lon_max.max():.1f}, latitude {inv.lat_min.min():.1f} to {inv.lat_max.max():.1f} (trips worldwide)")
    worst = inv.sort_values("stationary_frac", ascending=False).head(3)[["partition", "trip_id", "n_points", "stationary_frac", "duration_s"]]
    add("\nMost parked trips:\n\n" + md(worst))

    cs = pd.read_csv(R / "candidates_summary.csv", dtype={"trip_id": str})
    add("\n## Labels and candidates (results/candidates_summary.csv)\n")
    rows = []
    for part, g in cs.groupby("partition", sort=False):
        ex = g[~g.trip_id.isin(["00000054", "00000033"])]
        rows.append({"partition": part, "candidate_rows": int(g.n_candidate_rows.sum()),
                     "cands_per_point": g.n_candidate_rows.sum() / g.n_points.sum(),
                     "miss_rate": wavg(g.candidate_miss_frac, g.n_points),
                     "miss_rate_excl_54_33": wavg(ex.candidate_miss_frac, ex.n_points),
                     "label_differs_from_nearest": wavg(g.label_differs_from_nearest_frac, g.n_points)})
    add(md(pd.DataFrame(rows)))
    ct = pd.read_parquet(R / "candidates_student_test.parquet")
    top2 = ct[ct.f_dist_rank <= 1].pivot_table(index=["trip_id", "obs_idx"], columns="f_dist_rank", values="f_dist").dropna()
    add(f"\n- student_test points whose two nearest candidates tie in distance (two-way road): {((top2[1] - top2[0]).abs() < 0.01).mean():.4f}")
    add(f"- positive rate (student_test rows): {ct.label.mean():.4f}")
    means = ct.groupby("label")[[c for c in ct.columns if c.startswith("f_")]].mean().T
    means.columns = ["mean_wrong_arcs", "mean_true_arc"]
    add("\nFeature means, true vs wrong candidates (student_test):\n\n" + md(means.reset_index().rename(columns={"index": "feature"})))

    base = pd.read_csv(R / "baseline_nearest.csv", dtype={"trip_id": str})
    bt = base[base.partition == "student_test"]
    add("\n## Nearest-arc baseline (results/baseline_nearest.csv, student_test)\n")
    add(f"- top-1 all points {wavg(bt.top1_acc, bt.n_points):.4f}; ignoring direction {wavg(bt.top1_acc_ignore_direction, bt.n_points):.4f}; "
        f"route continuity {wavg(bt.route_continuity, bt.n_points):.4f}")

    add("\n## Five-model comparison (results/model_comparison.csv)\n")
    add(md(pd.read_csv(R / "model_comparison.csv")))
    add("\nTraining subset: every 5th GPS point of the 80 train trips, points whose reference arc is among the candidates "
        "(365,536 rows, 37,068 points). CV: 5-fold GroupKFold by trip. MLP training curve: results/plots/loss_curves.png.")

    cfg = json.loads((ROOT / "models/classifier_config.json").read_text())
    add("\n## Bayesian optimisation (results/tuning_comparison.csv, results/optuna_trials_mlp.csv)\n")
    tr = pd.read_csv(R / "optuna_trials_mlp.csv")
    add(f"- trials: {tr.state.value_counts().to_dict()}; best params: {cfg['best_params']}; best CV macro F1 {cfg['best_cv_macro_f1']:.4f}")
    add(md(pd.read_csv(R / "tuning_comparison.csv")))

    sw = pd.read_csv(R / "decoder_sweep_student_test.csv")
    add("\n## Decoder sweep (results/decoder_sweep_student_test.csv, 80 settings, student_test)\n")
    for k in ["beta_m", "emission_weight", "backward_tol_m"]:
        add(f"\n{k}:\n\n" + md(sw.groupby(k)[["acc_viterbi", "acc_viterbi_moving"]].mean().reset_index()))
    add("\nBest:\n\n" + md(sw.head(3)))

    vr = pd.read_csv(R / "viterbi_runs.csv", dtype={"trip_id": str})
    v = vr[vr.split == "student_test"]
    add("\n## Route reconstruction on student_test (results/viterbi_runs.csv, latest run per configuration)\n")
    rows = []
    for name, sel in [("HMM distance-only", (v.emission == "distance")),
                      ("MLP + HMM default decoder", (v.emission == "classifier") & (v.backward_tol_m == 10.0)),
                      ("MLP + HMM tuned decoder", (v.emission == "classifier") & (v.backward_tol_m == 30.0))]:
        g = v[sel].sort_values("run_at").drop_duplicates("trip_id", keep="last")
        rows.append({"method": name, "trips": len(g), "classifier_or_nearest_only_moving": wavg(g.acc_top1_moving, g.n_moving_points),
                     "hmm_moving": wavg(g.acc_viterbi_moving, g.n_moving_points), "hmm_all_points": wavg(g.acc_viterbi, g.n_ref_points),
                     "continuity_before": wavg(g.continuity_top1, g.n_ref_points), "continuity_after": wavg(g.continuity_viterbi, g.n_ref_points),
                     "continuity_reference": wavg(g.continuity_reference, g.n_ref_points)})
    add(md(pd.DataFrame(rows)))
    per = v[(v.emission == "classifier") & (v.backward_tol_m == 30.0)].sort_values("run_at").drop_duplicates("trip_id", keep="last")
    add("\nPer trip, tuned:\n\n" + md(per[["trip_id", "n_points", "n_moving_points", "acc_top1_moving", "acc_viterbi_moving", "acc_viterbi", "continuity_viterbi"]]))

    val = pd.read_csv(R / "decoder_validation_train.csv", dtype={"trip_id": str})
    add("\n## Decoder validation on train (results/decoder_validation_train.csv, out-of-fold MLP)\n")
    rows = []
    for name, g in val.groupby("setting", sort=False):
        ex = g[~g.trip_id.isin(["00000054", "00000033"])]
        rows.append({"setting": name, "mlp_only_moving": wavg(g.acc_top1_moving, g.n_moving_points),
                     "hmm_moving": wavg(g.acc_viterbi_moving, g.n_moving_points), "hmm_all": wavg(g.acc_viterbi, g.n_ref_points),
                     "hmm_moving_excl_54_33": wavg(ex.acc_viterbi_moving, ex.n_moving_points)})
    add(md(pd.DataFrame(rows)))
    p = val.pivot(index="trip_id", columns="setting", values="acc_viterbi_moving")
    d = p["tuned decoder"] - p["default decoder"]
    add(f"\n- tuned better on {(d > 0.001).sum()} trips, worse on {(d < -0.001).sum()}, same on {(d.abs() <= 0.001).sum()}")

    add("\n## Rejected experiment (results/experiment_heading_window.csv)\n")
    add(md(pd.read_csv(R / "experiment_heading_window.csv")))

    ea = error_analysis()
    m = ea[~ea.stationary]
    e = m[~m.correct]
    add("\n## Error analysis, final pipeline (results/error_analysis_student_test.csv)\n")
    add(f"- moving points {len(m)}, errors {len(e)} ({len(e) / len(m):.4f}); all points accuracy {ea.correct.mean():.4f}")
    add("- error types (moving): " + str((e.error_type.value_counts() / len(e)).round(3).to_dict()))
    adj = e[e.error_type == "adjacent arc"]
    add(f"- adjacent-arc errors within 10 m of the junction: {(adj.dist_to_junction_m < 10).mean():.3f}")
    add(f"- errors where predicted arc is closer to the GPS fix than the reference arc: {(e.dist_gps_to_pred_m < e.dist_gps_to_ref_m).mean():.3f}")
    add(f"- errors where GPS fix is > 30 m from its reference arc: {(e.dist_gps_to_ref_m > 30).mean():.3f}")
    add(f"- predicted arc lies on the reference route (all points): {ea.pred_on_route.mean():.4f}")
    add(f"- parked points accuracy {ea[ea.stationary].correct.mean():.4f}; parked share of all errors {(ea.stationary & ~ea.correct).sum() / (~ea.correct).sum():.3f}")

    # fixes the HMM corrected vs broke, from the final pipeline's per-point files (results/viterbi)
    pts = pd.concat([pd.read_csv(f).assign(trip_id=f.stem.split("_")[2])
                     for f in sorted((R / "viterbi").glob("student_test_*_points.csv"))])
    lab = pd.read_csv(R / "obs_labels_student_test.csv", dtype={"trip_id": str})
    pts = pts.merge(lab[["trip_id", "obs_idx", "stationary"]], on=["trip_id", "obs_idx"])
    mv = pts[~pts.stationary]
    clf_ok, hmm_ok = mv.top1_arc == mv.ref_arc, mv.pred_arc == mv.ref_arc
    add(f"\n## Classifier-only vs HMM per fix (moving, student_test, results/viterbi/*_points.csv)\n")
    add(f"- HMM fixed {int((~clf_ok & hmm_ok).sum())} fixes the MLP got wrong; broke {int((clf_ok & ~hmm_ok).sum())} the MLP got right; "
        f"both wrong {int((~clf_ok & ~hmm_ok).sum())}; both right {int((clf_ok & hmm_ok).sum())}")
    per_trip = mv.assign(fixed=~clf_ok & hmm_ok, broke=clf_ok & ~hmm_ok).groupby("trip_id")[["fixed", "broke"]].sum()
    add("\n" + md(per_trip.reset_index()))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(s) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
